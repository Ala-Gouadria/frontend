function delay(ms) {
  return new Promise((resolve) => globalThis.setTimeout(resolve, ms))
}

function cloneMemory(memory) {
  return { ...memory }
}

export const memoryApi = {
  async listMemories() {
    await delay(150)
    return MEMORIES.map(cloneMemory)
  },

  async getMemoryFilters() {
    await delay(80)
    return {
      categories: [...CATEGORIES],
      durations: [...DURATIONS],
      statuses: [...STATUSES],
    }
  },
}
